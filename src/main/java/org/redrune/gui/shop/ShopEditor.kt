        updateTable(shopList!!.selectedIndex)
    }

    /**
     * This method refreshes the shops shown on the [.shopList]
     */
    private fun refreshListing() {
        shopList!!.model = object : AbstractListModel<String?>() {
            override fun getSize(): Int {
                return localShops.size
            }

            override fun getElementAt(index: Int): String {
                val shop = getShopByIndex(index)
                if (shop == null) {
                    println("Unable to find shop by index $index")
                    return "N/A"
                }
                return shop.name
            }
        }
    }


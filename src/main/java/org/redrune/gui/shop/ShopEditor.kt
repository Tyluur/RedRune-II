    /**
     * Gets a shop by the index, this does not use the identifier value in the map, rather the order in which shops are
     * stored in the file.
     */
    private fun getShopByIndex(index: Int): Shop? {
        var count = 0
        for ((_, value) in localShops) {
            if (count == index) {
                return value
            }
            count++
        }
        return null
    }

    private fun updateTableItemsAfterInsertion() {
        val shop = selectedShop ?: throw IllegalStateException("Unable to update shop - unidentified shop.")
        val items: MutableList<Item> = LinkedList()
        for (count in 0 until itemTable!!.rowCount) {
            val name = itemTable!!.getValueAt(count, 0).toString()
            val itemId = itemTable!!.getValueAt(count, 1).toString()
            val itemAmount = itemTable!!.getValueAt(count, 2).toString()
            items.add(Item(itemId.toInt(), itemAmount.toInt()))
        }
        shop.items.clear()
        shop.items.addAll(items)
        updateTable(shopList!!.selectedIndex)
    }


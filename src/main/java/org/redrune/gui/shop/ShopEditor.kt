    /**
     * The items table is updated for the shop at the selected index
     */
    protected fun updateTable(index: Int) {
        val shop = getShopByIndex(index) ?: throw IllegalStateException("Unable to find shop by index $index")
        println("To update shop: " + shop.name)
        val model: DefaultTableModel = object : DefaultTableModel() {
            override fun isCellEditable(row: Int, column: Int): Boolean {
                return column != 0
            }
        }
        model.addColumn("Name")
        model.addColumn("Id")
        model.addColumn("Amount")
        if (shop.items != null) {
            for (item in shop.items) {
                if (item == null) {
                    continue
                }
                model.addRow(arrayOf<Any>(item.definitions.name, item.definitions.id, item.amount))
            }
        }
        identifierTextField!!.text = shop.identifier.toString()
        shopNameTextField!!.text = shop.name
        shopNameTextField!!.toolTipText = shop.name
        currencyNameTextField!!.text = shop.currencyName
        currencyNameTextField!!.toolTipText = shop.currencyName
        sellBackButton!!.isSelected = shop.isGeneralStore
        itemTable!!.model = model
        setTableModelListener()
        itemTable!!.scrollRectToVisible(
            itemTable!!.getCellRect(
                itemTable!!.rowCount - 1,
                itemTable!!.columnCount,
                true
            )
        )
    }

    /**
     * When events are fired on the table this method is invoked
     */
    private fun setTableModelListener() {
        itemTable!!.model.addTableModelListener(TableModelListener { e: TableModelEvent ->
            if (e.type != TableModelEvent.UPDATE) {
                return@TableModelListener
            }
            val selectedIndex = shopList!!.selectedIndex
            val shop = getShopByIndex(selectedIndex)
                ?: throw IllegalStateException("Unable to access shop with index $selectedIndex")
            val item = shop.items[e.firstRow]
            if (e.column == 1) {
                item.id = (itemTable!!.model.getValueAt(e.firstRow, e.column) as String).toInt()
                    .toShort().toInt()
            } else {
                item.amount = (itemTable!!.model.getValueAt(e.firstRow, e.column) as String).toInt()
            }
            println("Item [$item] updated")
        })
    }

    internal inner class TableRowTransferHandler : TransferHandler() {
        private val localObjectFlavor: DataFlavor
        private var indices: IntArray? = null
        private var addIndex = -1 //Location where items were added
        private var addCount = 0 //Number of items added.

        init {
            localObjectFlavor =
                ActivationDataFlavor(Array<Any>::class.java, DataFlavor.javaJVMLocalObjectMimeType, "Array of items")
        }

        override fun createTransferable(c: JComponent): Transferable {
            val table = c as JTable
            val model = table.model as DefaultTableModel
            val list: MutableList<Any> = ArrayList()
            indices = table.selectedRows
            if (indices != null) {
                for (i in indices!!) {
                    list.add(model.dataVector[i])
                }
            }
            val transferedObjects = list.toTypedArray()
            return DataHandler(transferedObjects, localObjectFlavor.mimeType)
        }

        override fun canImport(info: TransferSupport): Boolean {
            val table = info.component as JTable
            val isDropable = info.isDrop && info.isDataFlavorSupported(localObjectFlavor)
            table.cursor = if (isDropable) DragSource.DefaultMoveDrop else DragSource.DefaultMoveNoDrop
            return isDropable
        }

        override fun getSourceActions(c: JComponent): Int {
            return MOVE
        }

        override fun importData(info: TransferSupport): Boolean {
            if (!canImport(info)) {
                return false
            }
            val tdl = info.dropLocation as? JTable.DropLocation ?: return false
            val target = info.component as JTable
            val model = target.model as DefaultTableModel
            var index = tdl.row
            val max = model.rowCount
            if (index < 0 || index > max) {
                index = max
            }
            addIndex = index
            target.cursor = Cursor.getPredefinedCursor(Cursor.DEFAULT_CURSOR)
            try {
                val values = info.transferable.getTransferData(localObjectFlavor) as Array<Any>
                addCount = values.size
                for (i in values.indices) {
                    val idx = index++
                    model.insertRow(idx, values[i] as Vector<*>)
                    target.selectionModel.addSelectionInterval(idx, idx)
                }
                return true
            } catch (ex: UnsupportedFlavorException) {
                ex.printStackTrace()
            } catch (ex: IOException) {
                ex.printStackTrace()
            }
            return false
        }

        override fun exportDone(c: JComponent, data: Transferable, action: Int) {
            cleanup(c, action == MOVE)
        }

        //If the remove argument is true, the drop has been
        //successful and it's time to remove the selected items
        //from the list. If the remove argument is false, it
        //was a Copy operation and the original list is left
        //intact.
        protected fun cleanup(c: JComponent, remove: Boolean) {
            if (remove && indices != null) {
                c.cursor = Cursor.getPredefinedCursor(Cursor.DEFAULT_CURSOR)
                val model = (c as JTable).model as DefaultTableModel
                //If we are moving items around in the same list, we
                //need to adjust the indices accordingly, since those
                //after the insertion point have moved.
                if (addCount > 0) {
                    for (i in indices!!.indices) {
                        if (indices!![i] >= addIndex) {
                            indices!![i] += addCount
                        }
                    }
                }
                for (i in indices!!.indices.reversed()) {
                    model.removeRow(indices!![i])
                }
            }
            indices = null
            addCount = 0
            addIndex = -1
            updateTableItemsAfterInsertion()
        }
    }


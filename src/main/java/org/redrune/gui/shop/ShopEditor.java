    /**
     * The items table is updated for the shop at the selected index
     */
    protected void updateTable(int index) {
        final Shop shop = getShopByIndex(index);
        if (shop == null) {
            throw new IllegalStateException("Unable to find shop by index " + index);
        }
        System.out.println("To update shop: " + shop.getName());
        DefaultTableModel model = new DefaultTableModel() {

            @Override
            public boolean isCellEditable(int row, int column) {
                return column != 0;
            }
        };
        model.addColumn("Name");
        model.addColumn("Id");
        model.addColumn("Amount");
        if (shop.getItems() != null) {
            for (Item item : shop.getItems()) {
                if (item == null) {
                    continue;
                }
                model.addRow(new Object[]{item.getDefinitions().getName(), item.getDefinitions().getId(), item.getAmount()});
            }
        }
        identifierTextField.setText(String.valueOf(shop.getIdentifier()));
        shopNameTextField.setText(shop.getName());
        shopNameTextField.setToolTipText(shop.getName());
        currencyNameTextField.setText(shop.getCurrencyName());
        currencyNameTextField.setToolTipText(shop.getCurrencyName());
        sellBackButton.setSelected(shop.isGeneralStore());
        itemTable.setModel(model);
        setTableModelListener();
        itemTable.scrollRectToVisible(itemTable.getCellRect(itemTable.getRowCount() - 1, itemTable.getColumnCount(), true));
    }

    /**
     * When events are fired on the table this method is invoked
     */
    private void setTableModelListener() {
        itemTable.getModel().addTableModelListener(e -> {
            if (e.getType() != TableModelEvent.UPDATE) {
                return;
            }
            int selectedIndex = shopList.getSelectedIndex();
            Shop shop = getShopByIndex(selectedIndex);
            if (shop == null) {
                throw new IllegalStateException("Unable to access shop with index " + selectedIndex);
            }
            Item item = shop.getItems().get(e.getFirstRow());
            if (e.getColumn() == 1) {
                item.setId((short) Integer.parseInt((String) itemTable.getModel().getValueAt(e.getFirstRow(), e.getColumn())));
            } else {
                item.setAmount(Integer.parseInt((String) itemTable.getModel().getValueAt(e.getFirstRow(), e.getColumn())));
            }
            System.out.println("Item [" + item + "] updated");
        });
    }

    class TableRowTransferHandler extends TransferHandler {

        private final DataFlavor localObjectFlavor;

        private int[] indices;

        private int addIndex = -1; //Location where items were added

        private int addCount; //Number of items added.

        protected TableRowTransferHandler() {
            super();
            localObjectFlavor = new ActivationDataFlavor(Object[].class, DataFlavor.javaJVMLocalObjectMimeType, "Array of items");
        }

        @Override
        protected Transferable createTransferable(JComponent c) {
            JTable table = (JTable) c;
            DefaultTableModel model = (DefaultTableModel) table.getModel();
            java.util.List<Object> list = new ArrayList<>();
            indices = table.getSelectedRows();
            for (int i : indices) {
                list.add(model.getDataVector().get(i));
            }
            Object[] transferedObjects = list.toArray();
            return new DataHandler(transferedObjects, localObjectFlavor.getMimeType());
        }

        @Override
        public boolean canImport(TransferHandler.TransferSupport info) {
            JTable table = (JTable) info.getComponent();
            boolean isDropable = info.isDrop() && info.isDataFlavorSupported(localObjectFlavor);
            table.setCursor(isDropable ? DragSource.DefaultMoveDrop : DragSource.DefaultMoveNoDrop);
            return isDropable;
        }

        @Override
        public int getSourceActions(JComponent c) {
            return TransferHandler.MOVE;
        }

        @Override
        public boolean importData(TransferHandler.TransferSupport info) {
            if (!canImport(info)) {
                return false;
            }
            TransferHandler.DropLocation tdl = info.getDropLocation();
            if (!(tdl instanceof JTable.DropLocation)) {
                return false;
            }
            JTable.DropLocation dl = (JTable.DropLocation) tdl;
            JTable target = (JTable) info.getComponent();
            DefaultTableModel model = (DefaultTableModel) target.getModel();
            int index = dl.getRow();
            int max = model.getRowCount();
            if (index < 0 || index > max) {
                index = max;
            }
            addIndex = index;
            target.setCursor(Cursor.getPredefinedCursor(Cursor.DEFAULT_CURSOR));
            try {
                Object[] values = (Object[]) info.getTransferable().getTransferData(localObjectFlavor);
                addCount = values.length;
                for (int i = 0; i < values.length; i++) {
                    int idx = index++;
                    model.insertRow(idx, (Vector) values[i]);
                    target.getSelectionModel().addSelectionInterval(idx, idx);
                }
                return true;
            } catch (UnsupportedFlavorException | IOException ex) {
                ex.printStackTrace();
            }
            return false;
        }

        @Override
        protected void exportDone(JComponent c, Transferable data, int action) {
            cleanup(c, action == TransferHandler.MOVE);
        }

        //If the remove argument is true, the drop has been
        //successful and it's time to remove the selected items
        //from the list. If the remove argument is false, it
        //was a Copy operation and the original list is left
        //intact.
        protected void cleanup(JComponent c, boolean remove) {
            if (remove && indices != null) {
                c.setCursor(Cursor.getPredefinedCursor(Cursor.DEFAULT_CURSOR));
                DefaultTableModel model = (DefaultTableModel) ((JTable) c).getModel();
                //If we are moving items around in the same list, we
                //need to adjust the indices accordingly, since those
                //after the insertion point have moved.
                if (addCount > 0) {
                    for (int i = 0; i < indices.length; i++) {
                        if (indices[i] >= addIndex) {
                            indices[i] += addCount;
                        }
                    }
                }
                for (int i = indices.length - 1; i >= 0; i--) {
                    model.removeRow(indices[i]);
                }
            }
            indices = null;
            addCount = 0;
            addIndex = -1;
            updateTableItemsAfterInsertion();
        }
    }

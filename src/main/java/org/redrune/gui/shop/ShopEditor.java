    /**
     * Gets a shop by the index, this does not use the identifier value in the map, rather the order in which shops are
     * stored in the file.
     */
    private Shop getShopByIndex(int index) {
        int count = 0;
        for (Entry<Integer, Shop> entry : localShops.entrySet()) {
            if (count == index) {
                return entry.getValue();
            }
            count++;
        }
        return null;
    }

    private void updateTableItemsAfterInsertion() {
        Shop shop = getSelectedShop();
        if (shop == null) {
            throw new IllegalStateException("Unable to update shop - unidentified shop.");
        }
        List<Item> items = new LinkedList<>();
        for (int count = 0; count < itemTable.getRowCount(); count++) {
            String name = itemTable.getValueAt(count, 0).toString();
            String itemId = itemTable.getValueAt(count, 1).toString();
            String itemAmount = itemTable.getValueAt(count, 2).toString();
            items.add(new Item(Integer.parseInt(itemId), Integer.parseInt(itemAmount)));
        }
        shop.getItems().clear();
        shop.getItems().addAll(items);
        updateTable(shopList.getSelectedIndex());
    }


	/**
	 * This method refreshes the shops shown on the {@link #shopList}
	 */
	private void refreshListing() {
		shopList.setModel(new AbstractListModel<String>() {
			
			@Override
			public int getSize() {
				return localShops.size();
			}
			
			@Override
			public String getElementAt(int index) {
				Shop shop = getShopByIndex(index);
				if (shop == null) {
					System.out.println("Unable to find shop by index " + index);
					return "N/A";
				}
				return shop.getName();
			}
		});
	}
	
	/**
	 * Gets a sohp by the index, this does not use the identifier value in the map, rather the order in which shops are
	 * stored in the file.
	 */
	private Shop getShopByIndex(int index) {
		int count = 0;
		for (Entry<Integer, Shop> entry : localShops.entrySet()) {
			if (count == index) {
				return entry.getValue();
			}
			count++;
		}
		return null;
	}
	

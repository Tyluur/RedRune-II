	protected void updateTable(int index) {
		final Shop shop = getShopByIndex(index);
		if (shop == null) {
			throw new IllegalStateException("Unable to find shop by index " + index);
		}
		DefaultTableModel model = new DefaultTableModel() {
			
			@Override
			public boolean isCellEditable(int row, int column) {
				return column != 0;
			}
		};
		model.addColumn("Name");
		model.addColumn("Id");
		model.addColumn("Amount");
		if (shop != null && shop.getItems() != null) {
			for (Item item : shop.getItems()) {
				if (item == null) {
					continue;
				}
				model.addRow(new Object[] { item.getDefinitions().getName(), item.getDefinitions().getId(), item.getAmount() });
			}
		}
		identifierTextField.setText(String.valueOf(shop.getIdentifier()));
		shopNameTextField.setText(shop.getName());
		itemTable.setModel(model);
		setTableModelListener();
		itemTable.scrollRectToVisible(itemTable.getCellRect(itemTable.getRowCount() - 1, itemTable.getColumnCount(), true));
	}
	
